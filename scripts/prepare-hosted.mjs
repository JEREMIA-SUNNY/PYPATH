#!/usr/bin/env node
// Prepares the static assets the hosted site needs, from the single sources in src/ and python/:
//   public/harness.py         <- python/harness.py (the grading harness, unchanged)
//   public/pyodide-worker.mjs <- src/lib/runner/{parse,pyodide-core,pyodide.worker}.ts, flattened into one
//                                standalone ES module. Pyodide refuses to run inside the "classic" workers
//                                that Turbopack emits, so the worker must be served as a plain module script.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pub = path.join(root, "public");
mkdirSync(pub, { recursive: true });
copyFileSync(path.join(root, "python", "harness.py"), path.join(pub, "harness.py"));

const version = /PYODIDE_VERSION = "([^"]+)"/.exec(readFileSync(path.join(root, "src/lib/mode.ts"), "utf8"))[1];
const parts = ["parse.ts", "pyodide-core.ts", "pyodide.worker.ts"].map((f) => {
  const src = readFileSync(path.join(root, "src/lib/runner", f), "utf8");
  const js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
  return js
    .replace(/^import .* from "[^"]+";$/gm, "")
    .replace(/^export \{[^}]*\};?$/gm, "")
    .replace(/^export (default )?/gm, "");
});
const header = `// GENERATED by scripts/prepare-hosted.mjs. Do not edit.\nconst PYODIDE_CDN = "https://cdn.jsdelivr.net/pyodide/v${version}/full/";\n`;
writeFileSync(path.join(pub, "pyodide-worker.mjs"), header + parts.join("\n"));
